'use strict';
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path'),assert=require('node:assert/strict');
const dir=path.resolve(__dirname,'../apps/starbud-adventure');
const read=p=>fs.readFileSync(path.join(dir,p),'utf8');
const core=read('v05-core.js'),game=read('game.js'),html=read('index.html'),css=read('v05.css');
new vm.Script(core);new vm.Script(game);
const win={STARBUD_UI:{goal:(_,objects)=>objects[0]}};
vm.runInNewContext(core,{window:win});
const v=win.STARBUD_V05;
assert.ok(v);
const S={version:1,name:'原有玩家',avatar:2,role:0,coins:90,xp:167,flags:{bridge:true,foxTalk:true,treasure:true},bag:{wood:2,rope:0,crystal:1,seed:0},collected:['treeA'],awards:['rabbit'],x:9,y:3};
v.normalize(S);
assert.equal(S.version,1);assert.equal(S.name,'原有玩家');assert.equal(S.flags.bridge,true);
assert.equal(v.gatherBonus(S),2);assert.equal(S.v05.discoveries,1);
assert.equal(v.purchase(S,'boots').ok,true);assert.equal(S.coins,62);
assert.equal(v.travelDuration(S),49);
assert.equal(v.purchase(S,'boots').ok,false);assert.equal(S.coins,62);
assert.equal(v.purchase(S,'plant').ok,true);assert.equal(S.coins,50);
v.normalize(S);assert.equal(v.owns(S,'plant'),true);
assert.equal(v.toggleBoots(S),true);assert.equal(v.travelDuration(S),85);
assert.equal(S.xp,167);assert.deepEqual(S.collected,['treeA']);
const poor={coins:0};v.normalize(poor);assert.equal(v.purchase(poor,'compass').ok,false);
assert.ok(core.includes('重新建立角色'));
assert.ok(game.includes('showBridgePuzzle')&&game.includes('caveAction')&&game.includes('gardenAction'));
assert.ok(game.includes("if(S)window.STARBUD_V05?.normalize(S)"));
assert.ok(game.includes('window.STARBUD_V05?.gatherBonus(S)'));
assert.ok(html.indexOf('v05-core.js?v=0500')<html.indexOf('game.js?v=0500'));
assert.ok(html.includes('v05.css?v=0500')&&html.includes('小小冒險家 · v0.5'));
assert.ok(css.includes('grid-template-columns:1.03em .82em')&&css.includes('position:static!important'));
assert.ok(css.includes('body.bopo-on .dialog-body p')&&css.includes('@media(max-width:600px)'));
console.log('Starbud v0.5 migration, progression, old quests and bopomofo checks passed');
